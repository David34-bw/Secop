-- Esquema de SECOP RADAR. Compatible con H2 (modo PostgreSQL) y con
-- PostgreSQL. Se ejecuta en cada arranque: todo es "IF NOT EXISTS".
-- Las listas de los perfiles se guardan como texto JSON (["a","b"]).

CREATE TABLE IF NOT EXISTS users (
  id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email                  VARCHAR(254) NOT NULL UNIQUE,
  password_hash          VARCHAR(100),
  nombre                 VARCHAR(200),
  rol                    VARCHAR(20)  NOT NULL DEFAULT 'usuario',
  plan                   VARCHAR(20)  NOT NULL DEFAULT 'gratis',
  prueba_hasta           TIMESTAMP WITH TIME ZONE,
  gracia_hasta           TIMESTAMP WITH TIME ZONE,
  prepago_plan           VARCHAR(20),
  prepago_hasta          TIMESTAMP WITH TIME ZONE,
  suscripcion_estado     VARCHAR(40),
  email_verificado       BOOLEAN      NOT NULL DEFAULT TRUE,
  alertas_activas        BOOLEAN      NOT NULL DEFAULT TRUE,
  terminos_aceptados_at  TIMESTAMP WITH TIME ZONE,
  terminos_version       VARCHAR(10),
  privacidad_aceptada_at TIMESTAMP WITH TIME ZONE,
  privacidad_version     VARCHAR(10),
  created_at             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS perfiles (
  id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id              INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  nombre               VARCHAR(200) NOT NULL,
  categorias           VARCHAR(4000) NOT NULL DEFAULT '[]',
  palabras_clave       VARCHAR(8000) NOT NULL DEFAULT '[]',
  palabras_excluir     VARCHAR(8000) NOT NULL DEFAULT '[]',
  departamentos        VARCHAR(4000) NOT NULL DEFAULT '[]',
  ciudades             VARCHAR(4000) NOT NULL DEFAULT '[]',
  modalidades          VARCHAR(4000) NOT NULL DEFAULT '[]',
  tipos_contrato       VARCHAR(4000) NOT NULL DEFAULT '[]',
  tipos_entidad        VARCHAR(1000) NOT NULL DEFAULT '[]',
  rangos_valor         VARCHAR(1000) NOT NULL DEFAULT '[]',
  dias_min_restantes   INTEGER,
  profesion_id         VARCHAR(60),
  activo               BOOLEAN NOT NULL DEFAULT TRUE,
  desactivado_por_plan BOOLEAN NOT NULL DEFAULT FALSE,
  created_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS perfiles_user_idx ON perfiles (user_id);

CREATE TABLE IF NOT EXISTS procesos (
  id_del_proceso        VARCHAR(100) PRIMARY KEY,
  entidad               VARCHAR(1000),
  nombre                VARCHAR(4000),
  objeto                VARCHAR(20000),
  modalidad             VARCHAR(200),
  categoria             VARCHAR(100),
  tipo_contrato         VARCHAR(200),
  valor                 BIGINT,
  departamento          VARCHAR(200),
  ciudad                VARCHAR(200),
  estado_apertura       VARCHAR(100),
  estado_procedimiento  VARCHAR(100),
  respuestas            INTEGER,
  fecha_publicacion     TIMESTAMP WITH TIME ZONE,
  fecha_cierre          TIMESTAMP WITH TIME ZONE,
  url                   VARCHAR(2000),
  ordenentidad          VARCHAR(200),
  raw                   VARCHAR(1000000),
  ingresado_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS procesos_cierre_idx ON procesos (fecha_cierre);

CREATE TABLE IF NOT EXISTS coincidencias (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  perfil_id  INTEGER NOT NULL REFERENCES perfiles(id) ON DELETE CASCADE,
  proceso_id VARCHAR(100) NOT NULL REFERENCES procesos(id_del_proceso) ON DELETE CASCADE,
  score      INTEGER NOT NULL,
  notificado BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT coincidencias_unica UNIQUE (perfil_id, proceso_id)
);
CREATE INDEX IF NOT EXISTS coincidencias_proceso_idx ON coincidencias (proceso_id);

CREATE TABLE IF NOT EXISTS ingesta_log (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  corrida_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  leidos       INTEGER NOT NULL DEFAULT 0,
  nuevos       INTEGER NOT NULL DEFAULT 0,
  actualizados INTEGER NOT NULL DEFAULT 0,
  exito        BOOLEAN NOT NULL,
  error        VARCHAR(4000)
);

CREATE TABLE IF NOT EXISTS coincidencias_log (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  corrida_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  perfiles   INTEGER NOT NULL DEFAULT 0,
  procesos   INTEGER NOT NULL DEFAULT 0,
  nuevas     INTEGER NOT NULL DEFAULT 0,
  quitadas   INTEGER NOT NULL DEFAULT 0,
  exito      BOOLEAN NOT NULL,
  error      VARCHAR(4000)
);

CREATE TABLE IF NOT EXISTS alertas_envios (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       INTEGER REFERENCES users(id) ON DELETE SET NULL,
  enviado_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  coincidencias INTEGER NOT NULL,
  prueba        BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS alertas_log (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  corrida_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  candidatos          INTEGER NOT NULL DEFAULT 0,
  enviados            INTEGER NOT NULL DEFAULT 0,
  fallidos            INTEGER NOT NULL DEFAULT 0,
  omitidos_por_limite INTEGER NOT NULL DEFAULT 0,
  exito               BOOLEAN NOT NULL,
  error               VARCHAR(4000)
);

-- Datos del usuario como proponente en SECOP II (todo opcional).
CREATE TABLE IF NOT EXISTS proponentes (
  user_id               INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  tipo_persona          VARCHAR(40),
  tipo_documento        VARCHAR(60),
  numero_documento      VARCHAR(20),
  telefono              VARCHAR(20),
  departamento          VARCHAR(100),
  ciudad                VARCHAR(100),
  profesion             VARCHAR(150),
  titulo                VARCHAR(200),
  universidad           VARCHAR(200),
  matricula_profesional VARCHAR(40),
  anios_experiencia     INTEGER,
  resumen               VARCHAR(2000),
  registrado_secop      BOOLEAN NOT NULL DEFAULT FALSE,
  tiene_rup             BOOLEAN NOT NULL DEFAULT FALSE,
  numero_rup            VARCHAR(40),
  sigep_actualizada     BOOLEAN NOT NULL DEFAULT FALSE,
  actualizado_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Archivos que sube el usuario (cédula, RUT, certificados...). El archivo
-- va dentro de la base para verlo desde cualquier computador.
CREATE TABLE IF NOT EXISTS documentos (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  tipo           VARCHAR(40)  NOT NULL,
  nombre_archivo VARCHAR(255) NOT NULL,
  tipo_mime      VARCHAR(100),
  tamano         BIGINT       NOT NULL,
  contenido      BYTEA        NOT NULL,
  vence          DATE,
  subido_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS documentos_user_idx ON documentos (user_id);

-- Procesos a los que el usuario decidió presentarse, con su avance por
-- etapas. Los datos del proceso se copian para no perderlos.
CREATE TABLE IF NOT EXISTS postulaciones (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id             INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  proceso_id          VARCHAR(100) NOT NULL,
  entidad             VARCHAR(1000),
  objeto              VARCHAR(20000),
  modalidad           VARCHAR(200),
  valor               BIGINT,
  fecha_cierre        TIMESTAMP WITH TIME ZONE,
  url                 VARCHAR(2000),
  revisado            BOOLEAN NOT NULL DEFAULT FALSE,
  pliego_leido        BOOLEAN NOT NULL DEFAULT FALSE,
  notas               VARCHAR(4000),
  requisitos_extra    VARCHAR(8000) NOT NULL DEFAULT '[]',
  valor_ofertado      BIGINT,
  propuesta_nombre    VARCHAR(255),
  propuesta_contenido BYTEA,
  presentada_at       TIMESTAMP WITH TIME ZONE,
  resultado           VARCHAR(20),
  plazo_subsanar      DATE,
  desistida           BOOLEAN NOT NULL DEFAULT FALSE,
  created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT postulaciones_unica UNIQUE (user_id, proceso_id)
);
