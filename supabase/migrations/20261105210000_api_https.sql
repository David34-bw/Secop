-- SECOP RADAR: acceso por HTTPS (Edge Function "api").
-- Sesiones propias, límite de intentos de login, subidas a Storage y
-- columnas nuevas. NO se aplica sola: ver la guía de despliegue (fase 5).

-- Sesiones: solo se guarda el hash SHA-256 del token, nunca el token.
CREATE TABLE IF NOT EXISTS secop.sesiones (
  token_hash  TEXT PRIMARY KEY,
  usuario_id  INTEGER NOT NULL REFERENCES secop.users(id) ON DELETE CASCADE,
  creada      TIMESTAMPTZ NOT NULL DEFAULT now(),
  expira      TIMESTAMPTZ NOT NULL,
  ultimo_uso  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS sesiones_usuario_idx ON secop.sesiones (usuario_id);
CREATE INDEX IF NOT EXISTS sesiones_expira_idx ON secop.sesiones (expira);

-- Intentos de inicio de sesión (antes el límite vivía en la memoria de cada app).
CREATE TABLE IF NOT EXISTS secop.intentos_login (
  id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email   VARCHAR(254) NOT NULL,
  ip      VARCHAR(64)  NOT NULL,
  exito   BOOLEAN      NOT NULL,
  creado  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS intentos_login_email_idx ON secop.intentos_login (email, creado);
CREATE INDEX IF NOT EXISTS intentos_login_ip_idx ON secop.intentos_login (ip, creado);

-- Subidas a Storage pedidas y todavía sin confirmar (vencen en 2 horas).
CREATE TABLE IF NOT EXISTS secop.subidas_pendientes (
  id              UUID PRIMARY KEY,
  usuario_id      INTEGER NOT NULL REFERENCES secop.users(id) ON DELETE CASCADE,
  destino         VARCHAR(20) NOT NULL CHECK (destino IN ('documento', 'propuesta')),
  tipo            VARCHAR(40),
  postulacion_id  INTEGER REFERENCES secop.postulaciones(id) ON DELETE CASCADE,
  nombre          VARCHAR(255) NOT NULL,
  ext             VARCHAR(5)   NOT NULL,
  vence           DATE,
  ruta            TEXT NOT NULL,
  creada          TIMESTAMPTZ NOT NULL DEFAULT now(),
  expira          TIMESTAMPTZ NOT NULL DEFAULT now() + interval '2 hours'
);

-- Archivos: en modo API van a Storage (ruta); en modo JDBC siguen en la base (contenido).
ALTER TABLE secop.documentos ADD COLUMN IF NOT EXISTS ruta TEXT;
ALTER TABLE secop.documentos ALTER COLUMN contenido DROP NOT NULL;
DO $$ BEGIN
  ALTER TABLE secop.documentos ADD CONSTRAINT documentos_archivo_chk CHECK (contenido IS NOT NULL OR ruta IS NOT NULL);
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
ALTER TABLE secop.postulaciones ADD COLUMN IF NOT EXISTS propuesta_ruta TEXT;

-- Para que la app pida solo los procesos que cambiaron desde su última descarga.
ALTER TABLE secop.procesos ADD COLUMN IF NOT EXISTS actualizado_at TIMESTAMPTZ NOT NULL DEFAULT now();
CREATE INDEX IF NOT EXISTS procesos_actualizado_idx ON secop.procesos (actualizado_at);

-- Igual que las demás tablas de secop: sin acceso para anon/authenticated
-- (solo la Edge Function y el modo JDBC, que entran como postgres).
ALTER TABLE secop.sesiones ENABLE ROW LEVEL SECURITY;
ALTER TABLE secop.intentos_login ENABLE ROW LEVEL SECURITY;
ALTER TABLE secop.subidas_pendientes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON secop.sesiones, secop.intentos_login, secop.subidas_pendientes FROM anon, authenticated;

